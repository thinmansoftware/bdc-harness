/**
 * Tests for the check-completion recheck WIRING seams (bdc-harness #782,
 * Overseer App review finding at head 939d42f7 on 2026-09-07).
 *
 * THE BUG THESE PIN: `extractReviewSummary` is the only thing that can tell a
 * check-caused CHANGES_REQUESTED from a code-caused one, and it reads the
 * review work item's `result_body`. That body is `JSON.stringify(outcome)` for
 * a `SubmitOutcome` -- and the reviewer's posted finding text was not on that
 * type at all. A clean `changes_requested` sets no `reason` either, so the
 * function returned null, `verdictAuthorizesRecheck` refused the verdict, and
 * BOTH the webhook path and the stale sweep enqueued nothing. The re-review
 * this WO exists to deliver never happened.
 *
 * EVERY EXPECTED BODY HERE COMES FROM THE REAL SERIALIZER. The variants are
 * produced by running `runAndSubmitReview` against fake deps and stringifying
 * the outcome it actually returns -- never a hand-written literal, which would
 * pass while the persisted shape drifted underneath it.
 */
